#!/usr/bin/env python3
"""Generate the pin 19 write-acceptance experiments 46-49. Run with --no-trace.
All register state is loaded with pin 19 DRIVEN LOW (p19 0); only the write under test is made with it HIGH.
"""
src = open("tools/gen_decode_sweep.py").read().split('write("34')[0]
ns = {}; exec(src, ns)
baseline, fingerprint = ns["baseline"], ns["fingerprint"]
EV = ["m 1", "r"]


def write(name, comment, segs):
    out = ["# GENERATED by tools/gen_p19_map.py; do not edit by hand.", comment, "p19 0"]
    for label, cmds in segs:
        out += [f"mark {label}"] + cmds
    out.append("p19 0")
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


# 46: $8000 bits 5-7 matrix. obs: x=(a12 0,a10 1) z=(a12 0,a10 0) y=(a12 1,a10 1), rd 8000
def ctrl_of(s): return ((s >> 2) & 1) << 7 | ((s >> 1) & 1) << 6 | (s & 1) << 5
segs = []
for S in range(8):
    for T in range(8):
        segs.append((f"S={ctrl_of(S):02X} T={ctrl_of(T):02X}",
                     ["p19 0"] + (baseline() if T == 0 else []) + [f"w 8000 {ctrl_of(S):02X}", "p19 1", f"w 8000 {ctrl_of(T):02X}",
                      "a12 0", "ppu 1 0", "r", "ppu 0 0", "r", "a12 1", "ppu 1 0", "r", "rd 8000", "p19 0"]))
write("46_p19_ctrl_matrix", "# $8000 bits 5-7: start value S set low, then T written with pin 19 high.", segs)

# 47: value function
CH = [0x00, 0x55, 0xAA, 0xFF]; CH0 = [0x00, 0x54, 0xAA, 0xFE]; PR = [0x00, 0x0A, 0x15, 0x1F]
segs = []
for name, idx, Vs, obs in (("R0", 0, CH0, ["a12 0", "ppu 0 0", "r"]), ("R2", 2, CH, ["a12 1", "ppu 0 0", "r"]), ("R6", 6, PR, ["rd 8000"])):
    for V in Vs:
        for W in Vs:
            segs.append((f"reg={name} V={V:02X} W={W:02X}",
                         ["p19 0", f"w 8000 {idx:02X}", f"w 8001 {V:02X}", "p19 1", f"w 8001 {W:02X}"] + obs + ["p19 0"]))
for V in (0, 1):
    for W in (0x00, 0x01, 0x02, 0x03, 0xFE, 0xFF):
        segs.append((f"reg=A000 V={V:02X} W={W:02X}",
                     ["p19 0", f"w A000 {V:02X}", "p19 1", f"w A000 {W:02X}", "a12 0", "ppu 1 0", "r", "p19 0"]))
write("47_p19_value_function", "# Value function: start value V set low, W written high; result read from the outputs.", segs)

# 48: which register, index accepted?
segs = []
for n in (0, 1, 2, 3, 4, 5, 8, 9, 6, 7, 0xF):
    segs.append((f"idx={n:X} sel_low",
                 ["p19 0"] + baseline() + [f"w 8000 {0x20 | n:02X}", "p19 1", "w 8001 66", "p19 0"] + ["mark_fp"] ))
    segs.append((f"idx={n:X} sel_high",
                 ["p19 0"] + baseline() + ["w 8000 20", "p19 1", f"w 8000 {0x20 | n:02X}", "w 8001 66", "p19 0"] + ["mark_fp"]))
# expand fingerprint placeholder (fingerprint needs p19 irrelevant: read with pin low)
segs = [(l, [x for c in cmds for x in (fingerprint() if c == "mark_fp" else [c])]) for l, cmds in segs]
write("48_p19_register_accept", "# Each register written with pin 19 high: index selected low (sel_low) or written high (sel_high).", segs)

# 49: IRQ registers
segs = []
segs.append(("E000 ack: assert low, ack high",
             ["p19 0", "w E000 00", "w C000 01", "w C001 01", "w E001 00"] + EV * 12 + ["p19 1", "w E000 00", "r", "p19 0", "r"]))
segs.append(("E001 enable: disabled, enable high",
             ["p19 0", "w E000 00", "w C000 01", "w C001 01", "m 20", "r", "p19 1", "w E001 00", "r"] + EV * 30 + ["p19 0"]))
segs.append(("C001 restart: L=4 running, rewrite high at t=9",
             ["p19 0", "w E000 00", "w C000 04", "w C001 01", "w E001 00", "m 7", "r", "p19 1", "w C001 01", "r"] + EV * 40 + ["p19 0"]))
segs.append(("C000 latch: L=4 -> 1 high, then ack/enable low",
             ["p19 0", "w E000 00", "w C000 04", "w C001 01", "w E001 00"] + EV * 25 + ["w E000 00", "r", "w E001 00", "r",
              "p19 1", "w C000 01", "r", "p19 0"] + EV * 16 + ["w E000 00", "r", "w E001 00", "r"] + EV * 30))
write("49_p19_irq_registers", "# IRQ registers with pin 19 high (set and read as in the low case, F-018..F-033).", segs)
print("wrote 46-49")
