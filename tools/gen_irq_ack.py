#!/usr/bin/env python3
"""Generate $E000/$E001 edge-case experiments 26 (CPU mode) and 27 (A12 mode). Use --no-trace.
Reports: tools/irq_reload_report.py. 'actions' fire after the given M2 cycle (CPU) / pulse (A12) count.
"""
EV = ["m 1", "r"]
PULSE = ["a12 1", "m 2", "a12 0", "m 20", "r"]


def setup(L, mode):
    return ["w E000 00", f"w C000 {L:02X}", f"w C001 {mode:02X}", "w E001 00", "r"]


def cpu_seg(label, actions, n=60):
    c = setup(4, 1)
    t = 1                                   # cycles since $C001 (the $E001 write was cycle 1)
    while t < n:
        if t in actions:
            for a in actions[t]:
                c += [a, "r"]
                t += 1
        else:
            c += EV; t += 1
    return (label, c)


def a12_seg(label, actions, pulses=10, pre=None):
    c = setup(1, 0) + (pre or []) + ["m 64"]
    for p in range(0, pulses + 1):
        if p in actions:
            for a in actions[p]:
                c += [a, "r"]
        if p < pulses:
            c += PULSE
    return (label, c)


def write(name, comment, segs):
    out = ["# GENERATED by tools/gen_irq_ack.py; do not edit by hand.", comment]
    for label, cmds in segs:
        out += [f"mark {label}"] + cmds
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


s = [cpu_seg("control (expiries at 22, then stays low)", {})]
for j in (5, 10, 15):
    s.append(cpu_seg(f"e001_again@{j}", {j: ["w E001 00"]}))
s.append(cpu_seg("e000@10,e001@11 (re-enabled before expiry)", {10: ["w E000 00", "w E001 00"]}))
s.append(cpu_seg("e000@10,e001@30 (disabled across expiry 22)", {10: ["w E000 00"], 30: ["w E001 00"]}))
s.append(cpu_seg("e000@10 only (never re-enabled)", {10: ["w E000 00"]}))
s.append(cpu_seg("after assert: e001@26 (no e000)", {26: ["w E001 00"]}))
s.append(cpu_seg("after assert: e000@26,e001@27", {26: ["w E000 00", "w E001 00"]}))
s.append(cpu_seg("after assert: e000@26 only", {26: ["w E000 00"]}))
for d in (0x00, 0x01, 0x80, 0xFF):
    s.append(cpu_seg(f"data E000/E001={d:02X}: ack@26, enable@28",
                     {26: [f"w E000 {d:02X}"], 28: [f"w E001 {d:02X}"]}))
write("26_irq_ack_cpu", "# CPU mode L=4: $E000/$E001 timing and data edge cases. Expiries at t=22, 42, 62 if enabled.", s)

s = [a12_seg("control (assert at pulse 3, then stays)", {})]
s.append(a12_seg("disabled before pulses, enable after pulse 6", {}, pre=["w E000 00"]) if False else
         ("disable before pulses; enable after pulse 6",
          setup(1, 0)[:-1] + ["w E000 00", "r", "m 64"] +
          PULSE * 6 + ["w E001 00", "r"] + PULSE * 4))
s.append(a12_seg("ack+enable after pulse 3", {3: ["w E000 00", "w E001 00"]}))
s.append(a12_seg("ack only after pulse 3", {3: ["w E000 00"]}))
s.append(a12_seg("e000+e001 after pulse 1 (mid-count)", {1: ["w E000 00", "w E001 00"]}))
s.append(a12_seg("e000 after 1, e001 after 2", {1: ["w E000 00"], 2: ["w E001 00"]}))
s.append(a12_seg("e001 again after pulse 1", {1: ["w E001 00"]}))
write("27_irq_ack_a12", "# A12 mode L=1 (assert at pulse 3): $E000/$E001 edge cases and repeat edges.", s)
print("wrote 26, 27")
