#!/usr/bin/env python3
"""Generate experiments/38_regression.txt: a self-contained behaviour fingerprint for comparing board
configurations (e.g. SW1C on vs off). It loads a known register state first, so repeats are comparable.
Sections: CHR/PRG mapping fingerprints for six $8000 modes; CPU-mode IRQ (L=1, L=4); A12 filter (G=16, G=15);
PRG /CE truth table. Run with --no-trace.
"""
import importlib.util, sys
spec = importlib.util.spec_from_file_location("g", "tools/gen_decode_sweep.py")
src = open("tools/gen_decode_sweep.py").read().split("write(\"34")[0]
ns = {}; exec(src, ns)
baseline, fingerprint = ns["baseline"], ns["fingerprint"]
EV = ["m 1", "r"]
PULSE = ["a12 1", "m 2", "a12 0"]


def setup(L, mode):
    return ["w E000 00", f"w C000 {L:02X}", f"w C001 {mode:02X}", "w E001 00", "r"]


out = ["# GENERATED by tools/gen_regression.py; do not edit by hand.",
       "# Behaviour fingerprint for comparing configurations. Self-contained; deterministic from a defined state.",
       "mark prelude"] + baseline() + ["w E000 00", "r"]
for c in (0x00, 0x20, 0x40, 0x80, 0xA0, 0xE0):
    out += [f"mark mapping ctrl={c:02X}", f"w 8000 {c:02X}"] + fingerprint()
for L, n in ((1, 12), (4, 26)):
    out += [f"mark cpu irq L={L}"] + setup(L, 1) + EV * n
for G in (16, 15):
    out += [f"mark a12 L=1 G={G}"] + setup(1, 0) + ["m 64"]
    for _ in range(6):
        out += PULSE + [f"m {G}", "r"]
out += ["mark ce truth table"]
for m2 in (0, 1):
    for rw in (0, 1):
        for rs in (0, 1):
            out.append(f"bus {m2} {rw} {rs}")
out += ["bus 0 1 1", "w E000 00", "r"]
open("experiments/38_regression.txt", "w").write("\n".join(out) + "\n")
print(len(out), "lines")
