#!/usr/bin/env python3
"""Generate IRQ reload / mode-switch experiments 22-25. All run with --no-trace (explicit 'r').
PULSE = A12 high 2 M2 cycles, low 20 (passes the 16-cycle filter, see F-022); EV = one M2 cycle + read.
"""
PULSE = ["a12 1", "m 2", "a12 0", "m 20", "r"]
EV = ["m 1", "r"]


def write(name, comment, segs):
    out = ["# GENERATED by tools/gen_irq_reload.py; do not edit by hand.", comment]
    for label, cmds in segs:
        out += [f"mark {label}"] + cmds
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


def setup(L, mode):
    # Disable, set the latch, write $C001, THEN enable, so a leftover counter cannot assert /IRQ first.
    # t counts from the $C001 write: the $E001 write is cycle 1.
    return ["w E000 00", f"w C000 {L:02X}", f"w C001 {mode:02X}", "w E001 00", "r"]


# 22: $C001 rewrite in CPU mode, L=4 (first expiry 22 cycles after $C001)
segs = []
for j in [0, 2, 5, 10, 15, 19, 21, 25]:
    c = setup(4, 1) + ([f"m {j}", "r"] if j else []) + ["w C001 01", "r"] + EV * 45
    segs.append((f"c001_rewrite j={j}", c))
write("22_c001_rewrite_cpu", "# CPU mode, L=4: rewrite $C001 after j cycles. t counts from the LAST $C001 write.", segs)

# 23: $C000 write while counting, L=4 -> new latch 1. First expiry at 22; ack+enable at ~26 and watch the second.
segs = []
for j in [0, 1, 2, 3, 4, 6, 10, 15]:
    t_before = j + 2                                   # cycles since C001 incl. $E001 and the $C000 write
    c = setup(4, 1) + ([f"m {j}", "r"] if j else []) + ["w C000 01", "r"]
    c += EV * (26 - t_before) + ["w E000 00", "r", "w E001 00", "r"] + EV * 45
    segs.append((f"latch_change j={j} L4->1", c))
c = setup(4, 1) + EV * 25 + ["w E000 00", "r", "w E001 00", "r"] + EV * 45
segs.append(("latch_change none (control, L=4)", c))
write("23_latch_change_cpu", "# CPU mode: $C000 4 -> 1 after j cycles (no $C001). ack+enable at t~26, second expiry shows the period.", segs)

# 24: mode switches
segs = []
for j in [0, 8, 15]:
    segs.append((f"cpu_to_a12 j={j}", setup(4, 1) + ([f"m {j}", "r"] if j else []) + ["w C001 00", "r"] + PULSE * 10))
for j in [0, 2, 4]:
    segs.append((f"a12_to_cpu j={j}", setup(4, 0) + ["m 64"] + PULSE * j + ["w C001 01", "r"] + EV * 45))
for j in [1, 2, 3, 4]:
    segs.append((f"a12_same_mode j={j}", setup(4, 0) + ["m 64"] + PULSE * j + ["w C001 00", "r"] + PULSE * 10))
segs.append(("a12_control j=0", setup(4, 0) + ["m 64"] + PULSE * 10))
write("24_irq_mode_switch", "# Mode switches at $C001 mid-count (L=4). 'a12_same_mode' = $C001=00 again after j pulses.", segs)

# 25: $C001 data bits
segs = []
for d in [0x00, 0x02, 0x04, 0x10, 0x80, 0xFE]:
    segs.append((f"c001_data={d:02X} (bit0=0)", setup(2, d) + ["m 64"] + PULSE * 8))
for d in [0x01, 0x03, 0x05, 0x81, 0xFF]:
    segs.append((f"c001_data={d:02X} (bit0=1)", setup(2, d) + EV * 30))
write("25_c001_data_bits", "# $C001 data values, L=2: bit0=0 -> A12 mode (expect IRQ at pulse 4), bit0=1 -> CPU mode (expect 14 cycles).", segs)
print("wrote 22-25")
