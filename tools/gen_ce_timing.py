#!/usr/bin/env python3
"""Generate experiments/09_ce_timing.txt: PRG /CE for every (M2, R/W, /ROMSEL) state, reached from
every other state (64 transitions). If /CE is a pure function of the current pins, a target's
result is the same for every predecessor; any difference means latching or edge dependence.
All at $E000 (A13=1, A14=1, A0=0) so that the write combination only hits the IRQ acknowledge.
"""
import itertools
STATES = list(itertools.product((0, 1), repeat=3))        # (M2, RW, ROMSEL_N)
out = ["# GENERATED by tools/gen_ce_timing.py; do not edit by hand.",
       "# 'mark pre=M2RWROMSEL_N target=M2RWROMSEL_N', then the two states in order.",
       "bus 0 1 1"]
for tgt in STATES:
    for pre in STATES:
        out.append(f"mark pre={''.join(map(str, pre))} target={''.join(map(str, tgt))}")
        out.append("bus " + " ".join(map(str, pre)))
        out.append("bus " + " ".join(map(str, tgt)))
out.append("bus 0 1 1")
open("experiments/09_ce_timing.txt", "w").write("\n".join(out) + "\n")
print(f"wrote experiments/09_ce_timing.txt: {len(out)} lines")
