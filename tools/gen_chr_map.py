#!/usr/bin/env python3
"""Generate experiments/05_chr_map.txt: CHR address outputs for every PPU A10-A12 combination,
for each bank-select mode (bit 5 = 1 KB CHR mode, bit 7 = A12 inversion) and two value sets.

Every register gets a distinct value, so the CHR byte read back identifies which register
drives that PPU window. Value set 'odd' sets bit 0 of every value to show how bit 0 is used.
"""
import sys

REGS = [0, 1, 2, 3, 4, 5, 8, 9]                       # index written to $8000 bits 0-3
EVEN = {0: 0x10, 1: 0x30, 2: 0x50, 3: 0x70, 4: 0x90, 5: 0xB0, 8: 0xD0, 9: 0xF0}
CTRLS = [0x00, 0x20, 0x80, 0xA0]                      # bit 7 = inversion, bit 5 = 1 KB mode

out = ["# GENERATED by tools/gen_chr_map.py; do not edit by hand.",
       "# CHR_A10-A17 for all PPU A10-A12 combinations vs mode, register and value set.",
       "# Segment the log by 'mark' rows: 'ctrl=XX vals=even|odd'.",
       "ppu 0 0", "a12 0"]
for ctrl in CTRLS:
    for vs in ("even", "odd"):
        out.append(f"mark ctrl={ctrl:02X} vals={vs}")
        for r in REGS:
            val = EVEN[r] | (1 if vs == "odd" else 0)
            out.append(f"w 8000 {ctrl | r:02X}")
            out.append(f"w 8001 {val:02X}")
        out.append("a12 0")
        for a11 in (0, 1):
            for a10 in (0, 1):
                out.append(f"ppu {a10} {a11}")
        out.append("a12 1")
        for a11 in (0, 1):
            for a10 in (0, 1):
                out.append(f"ppu {a10} {a11}")
        out += ["a12 0", "ppu 0 0"]
open("experiments/05_chr_map.txt", "w").write("\n".join(out) + "\n")
print(f"wrote experiments/05_chr_map.txt: {len(out)} lines")
