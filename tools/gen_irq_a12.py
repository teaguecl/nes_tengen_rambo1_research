#!/usr/bin/env python3
"""Generate A12-mode IRQ experiments 31-33. Use --no-trace; report with tools/irq_reload_report.py.
PULSE = A12 high 2 M2 cycles, low 20 (passes the 16-cycle filter, F-022).
31: power-on latch (FF) in A12 mode: expiry expected at pulse 257 (needs NO $C000 write since power-up).
32: repeat period for L = 2, 3, 4 (first expiry L+2, then every L+1), ack+enable after each expiry.
33: when does the A12-mode counter take the latch: $C000 4 -> 1 written at different points.
"""
PULSE = ["a12 1", "m 2", "a12 0", "m 20"]
PULSE_R = PULSE + ["r"]


def setup(L, mode):
    s = ["w E000 00"]
    if L is not None:
        s.append(f"w C000 {L:02X}")
    return s + [f"w C001 {mode:02X}", "w E001 00", "r"]


def write(name, comment, segs):
    out = ["# GENERATED by tools/gen_irq_a12.py; do not edit by hand.", comment]
    for label, cmds in segs:
        out += [f"mark {label}"] + cmds
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


# 31: power-on latch, A12 mode. 250 unread pulses, then read after each.
c = setup(None, 0) + ["m 64"] + PULSE * 250 + PULSE_R * 14 + ["w E000 00", "r"]
write("31_a12_poweron_latch", "# A12 mode with the power-on latch (no $C000 written): expect /IRQ at pulse 257.", [("a12 power-on latch", c)])

# 32: repeat period for L > 1
segs = []
for L in (2, 3, 4):
    first, period = L + 2, L + 1
    n_exp = 3
    acks = [first + k * period + 1 for k in range(n_exp - 1)]       # one pulse after each expiry
    c = setup(L, 0) + ["m 64"]
    for p in range(1, first + (n_exp - 1) * period + 3):
        c += PULSE_R
        if p in acks:
            c += ["w E000 00", "r", "w E001 00", "r"]
    segs.append((f"period L={L}: expect expiries at pulses {first}, {first+period}, {first+2*period}", c))
write("32_a12_period", "# A12 mode: repeat period for L > 1; ack+enable one pulse after each expected expiry.", segs)

# 33: latch-load timing. Initial L=4 (first expiry at pulse 6 if used), then $C000 := 1 (first expiry at 3).
segs = []
variants = [
    ("C000 at t=2 (right after E001)", [], 0),
    ("C000 at t~7 (m 5)", ["m 5"], 0),
    ("C000 at t~8 (m 6)", ["m 6"], 0),
    ("C000 at t~25 (m 23), before pulse 1", ["m 23"], 0),
    ("C000 after pulse 1", [], 1),
    ("C000 after pulse 2", [], 2),
    ("C000 after pulse 4", [], 4),
]
for label, pre, after_p in variants:
    c = setup(4, 0) + pre
    if after_p == 0:
        c += ["w C000 01", "r", "m 64"] + PULSE_R * 7
    else:
        c += ["m 64"] + PULSE_R * after_p + ["w C000 01", "r"] + PULSE_R * (9 - after_p)
    c += ["w E000 00", "r", "w E001 00", "r"] + PULSE_R * 6
    segs.append((label, c))
write("33_a12_latch_load", "# A12 mode: $C000 4 -> 1 written at different times; then ack+enable and a few more pulses.", segs)
print("wrote 31-33")
