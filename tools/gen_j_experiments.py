#!/usr/bin/env python3
"""Generate jig experiments 57-59 (design: docs/test_rom_design.md, section 7). Run each with --no-trace; report with
tools/irq_reload_report.py (t = M2 cycles and p = A12 pulses since the last $C001 write, one line per IRQ_N change).
57 (J2): A12 mode, filter NOT full at $C001, L = 0, 1, 2. Expect /IRQ at pulse L+1 when not full, L+2 when full (F-021, F-052).
58 (J3): A12 mode, repeat period for L = 5..16 (F-037 covers L = 2..4). Filter filled first. Expect expiries at L+2, 2L+3, 3L+4.
59 (J4): CPU mode L = 4, $C001 := 0 (switch to A12) written t cycles after $E001, t spanning the CPU first expiry (22 cycles
    after the CPU-mode $C001). Records whether the pending expiry still fires, whether the CPU counter keeps running, and
    at which A12 pulse the next expiry comes.
"""
PULSE = ["a12 1", "m 2", "a12 0", "m 20"]
PULSE_R = PULSE + ["r"]


def write(name, comment, segs):
    out = ["# GENERATED by tools/gen_j_experiments.py; do not edit by hand.", comment, "p19 0"]
    for label, cmds in segs:
        out += [f"mark {label}"] + cmds
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


# 57 / J2
segs = []
for L in (0, 1, 2):
    for n in (0, 6, 12, 20):
        c = ["a12 0", "w E000 00", "a12 1", "m 1", "a12 0"] + ([f"m {n}"] if n else []) + \
            [f"w C000 {L:02X}", "w C001 00", "w E001 00", "m 64"] + PULSE_R * 5
        full = "full" if n >= 15 else "not full"
        segs.append((f"J2 L={L} n={n} low falls before C001 (filter {full}); expect /IRQ at pulse "
                     f"{L + 2 if n >= 15 else L + 1}", c))
write("57_a12_nonfull_low_latch", "# J2: A12 mode, filter not full at $C001, L = 0, 1, 2.", segs)

# 58 / J3
segs = []
for L in range(5, 17):
    first, period = L + 2, L + 1
    n_exp = 3
    acks = [first + k * period + 1 for k in range(n_exp - 1)]
    c = ["a12 0", "m 20", "w E000 00", f"w C000 {L:02X}", "w C001 00", "w E001 00", "r", "m 64"]
    for p in range(1, first + (n_exp - 1) * period + 3):
        c += PULSE_R
        if p in acks:
            c += ["w E000 00", "r", "w E001 00", "r"]
    segs.append((f"J3 period L={L}: expect expiries at pulses {first}, {first + period}, {first + 2 * period}", c))
write("58_a12_period_l5_16", "# J3: A12 mode period for L = 5..16 (full filter), ack+enable one pulse after each expected expiry.", segs)

# 59 / J4
segs = []
for t in range(10, 29):
    c = ["a12 0", "m 20", "w E000 00", "w C000 04", "w C001 01", "w E001 00", f"m {t}", "r",
         "w C001 00", "r", "m 2", "r", "m 8", "r", "m 20", "r", "m 20", "r",
         "w E000 00", "r", "w E001 00", "r"] + PULSE_R * 8
    segs.append((f"J4 L=4 switch to A12 at t={t + 1} cycles after the CPU-mode $C001 (CPU first expiry expected at 22)", c))
write("59_cpu_to_a12_switch", "# J4: CPU mode L=4 then $C001 := 0 near the first expiry.", segs)
print("wrote 57-59")
