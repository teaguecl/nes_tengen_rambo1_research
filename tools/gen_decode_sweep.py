#!/usr/bin/env python3
"""Generate register-decode sweep experiments 34-37. Run with --no-trace; report: tools/decode_report.py.

Each segment: load a known baseline into R0-R5, R8, R9, R6, R7, RF and $A000, apply ONE action, then take a
fingerprint (CHR byte for 8 combinations of PPU A12/A11/A10, PRG bank at the 4 windows, CIRAM_A10 for the
4 PPU A10/A11 combinations). Segment 'none' is the unchanged baseline for comparison.
Baseline control byte = $20 (1 KB CHR mode, no inversion, PRG mode 0).
"""
BASE = {0: 0x10, 1: 0x30, 2: 0x50, 3: 0x70, 4: 0x90, 5: 0xB0, 8: 0xD0, 9: 0xF0, 6: 0x05, 7: 0x0A, 0xF: 0x14}
CTRL0 = 0x20


def baseline():
    c = []
    for idx, v in BASE.items():
        c += [f"w 8000 {CTRL0 | idx:02X}", f"w 8001 {v:02X}"]
    return c + ["w 8000 20", "w A000 00"]


def fingerprint():
    c = []
    for a12 in (0, 1):
        c.append(f"a12 {a12}")
        for a11 in (0, 1):
            for a10 in (0, 1):
                c += [f"ppu {a10} {a11}", "r"]
    c += ["a12 0", "ppu 0 0", "rd 8000", "rd A000", "rd C000", "rd E000"]
    return c


def write(name, comment, segs):
    out = ["# GENERATED by tools/gen_decode_sweep.py; do not edit by hand.", comment]
    for label, action in segs:
        out += [f"mark {label}"] + baseline() + action + fingerprint()
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


write("34_decode_index", "# $8000 index 0-15 then $8001 = 66 (CHR 66, PRG 06).",
      [("none", [])] + [(f"idx={i:X} val=66", [f"w 8000 {CTRL0 | i:02X}", "w 8001 66"]) for i in range(16)])
write("35_decode_ctrl_bits", "# $8000 high nibble (bits 4-7) with index 0 and no $8001 write.",
      [("none", [])] + [(f"ctrl={c:02X}", [f"w 8000 {c:02X}"]) for c in range(0x00, 0x100, 0x10)])
write("36_decode_a000_data", "# $A000 data values (CIRAM_A10 responds to PPU A10/A11).",
      [("none", [])] + [(f"a000={d:02X}", [f"w A000 {d:02X}"]) for d in (0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0xFE, 0xFF)])
write("37_decode_a001_data", "# $A001 data values: any visible effect on the mapping?",
      [("none", [])] + [(f"a001={d:02X}", [f"w A001 {d:02X}"]) for d in (0x00, 0x01, 0x40, 0x80, 0xC0, 0xFF)])
print("wrote 34-37")
