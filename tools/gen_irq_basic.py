#!/usr/bin/env python3
"""Generate experiments 16 (CPU-cycle mode) and 17 (A12 scanline mode): events until /IRQ asserts.

Setup per latch value L:  $E000 (acknowledge+disable)  $C000=L  $C001=mode  $E001 (enable)
then one event at a time with the outputs read after each.
 16: mode 1 (CPU cycles): event = one idle M2 cycle ('m 1').
 17: mode 0 (A12): event = one PPU A12 pulse followed by GAP idle M2 cycles ('a 1 GAP').
Note: every register write is itself one M2 cycle ('w'), so CPU-cycle counts include the cycles of the
writes made after enabling (the $E001 write itself is the last one before the first event).
"""
import sys

def make(name, comment, latches, event, count, mode):
    event = event if isinstance(event, list) else [event]
    out = ["# GENERATED by tools/gen_irq_basic.py; do not edit by hand.", comment]
    for L in latches:
        out += [f"mark L={L:02X} mode={mode}", "w E000 00", f"w C000 {L:02X}", f"w C001 {mode:02X}", "w E001 00"]
        out += event * count
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")

make("16_irq_cpu_cycle", "# CPU-cycle mode ($C001=01): idle M2 cycles until /IRQ asserts, per latch value.",
     [0x01, 0x02, 0x03, 0x04, 0x08], "m 1", 48, 1)
make("17_irq_a12", "# A12 mode ($C001=00): A12 high for 4 M2 cycles, low for 8, until /IRQ asserts, per latch value.",
     [0x01, 0x02, 0x03, 0x04], ["a12 1", "m 4", "a12 0", "m 8", "r"], 20, 0)
print("wrote experiments 16, 17")
