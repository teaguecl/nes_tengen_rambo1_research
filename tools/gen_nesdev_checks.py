#!/usr/bin/env python3
"""Generate the NESdev-verification experiments 51-54 (see docs/nesdev_verification.md). Run with --no-trace.
51: R8/R9 only active when K=1? Do they keep their value across K changes?
52: A12-mode IRQ latency: when does /IRQ go low relative to M2 edges after the counting A12 rise?
53: A12 filter shape (4-bit counter model): fall vs rise sampling, high-phase shape, swallow-after-$C001 reset.
54: Does $A001 affect the IRQ counter or /IRQ?
"""
src = open("tools/gen_decode_sweep.py").read().split('write("34')[0]
ns = {}; exec(src, ns)
baseline, fingerprint = ns["baseline"], ns["fingerprint"]
EV = ["m 1", "r"]
PULSE = ["a12 1", "m 2", "a12 0", "m 20", "r"]


def write(name, comment, segs, prelude=("p19 0",)):
    out = ["# GENERATED by tools/gen_nesdev_checks.py; do not edit by hand.", comment] + list(prelude)
    for label, cmds in segs:
        out += [f"mark {label}"] + cmds
    open(f"experiments/{name}.txt", "w").write("\n".join(out) + "\n")


# ---- 51: R8/R9 gating by K
segs = [("A K=1 baseline (R8=D0 R9=F0)", baseline() + fingerprint()),
        ("B write R8:=44 R9:=46 while K=0, then show K=0",
         baseline() + ["w 8000 08", "w 8001 44", "w 8000 09", "w 8001 46", "w 8000 00"] + fingerprint()),
        ("C switch to K=1 without rewriting R8/R9",
         baseline() + ["w 8000 08", "w 8001 44", "w 8000 09", "w 8001 46", "w 8000 20"] + fingerprint()),
        ("D write R8:=55 R9:=57 while K=1",
         baseline() + ["w 8000 28", "w 8001 55", "w 8000 29", "w 8001 57", "w 8000 20"] + fingerprint()),
        ("E ...then K=0 then K=1 again, no rewrite",
         baseline() + ["w 8000 28", "w 8001 55", "w 8000 29", "w 8001 57", "w 8000 00", "w 8000 20"] + fingerprint())]
write("51_k_gates_r8_r9", "# Are R8/R9 writable and retained when K=0?", segs)

# ---- 52: A12 latency
def lat_setup():
    return ["a12 0", "m 20", "w E000 00", "w C000 00", "w C001 00", "w E001 00", "m 64"] + ["a12 1", "m 2", "a12 0", "m 20", "r"]   # filter full at $C001, so pulse 1 is swallowed
def steps(lst): return ["wseq clear"] + [f"wseq add {s} T=1 S" for s in lst] + ["wseq run"]
segs = [
    ("latency A: A12 rises while M2 low", lat_setup() + steps(["RW=1 M2=0 ROMSEL=1 A12=0", "A12=1", "M2=1", "M2=0", "M2=1", "M2=0", "M2=1", "M2=0", "A12=0"])),
    ("latency B: A12 rises while M2 high", lat_setup() + steps(["RW=1 M2=0 ROMSEL=1 A12=0", "M2=1", "A12=1", "M2=0", "M2=1", "M2=0", "M2=1", "M2=0", "A12=0"])),
    ("latency C: A12 drops again after fall #1", lat_setup() + steps(["RW=1 M2=0 ROMSEL=1 A12=0", "A12=1", "M2=1", "M2=0", "A12=0", "M2=1", "M2=0", "M2=1", "M2=0"])),
    ("latency D: A12 drops during M2 high after fall #1", lat_setup() + steps(["RW=1 M2=0 ROMSEL=1 A12=0", "A12=1", "M2=1", "M2=0", "M2=1", "A12=0", "M2=0", "M2=1", "M2=0"])),
]
write("52_a12_latency", "# L=0, A12 mode, second counted pulse stepped by M2 edge; sample after every step.", segs)

# ---- 53: A12 filter shape
def seg_steps(high, lstyle, F, hc=1):
    s = []
    if high == "normal":
        s += ["A12=1", "M2=1", "M2=0"] + ["M2=1", "M2=0"] * (hc - 1)
        if lstyle == "A": s += ["A12=0"] + ["M2=1", "M2=0"] * F
        else:             s += ["M2=1", "A12=0", "M2=0"] + ["M2=1", "M2=0"] * (F - 1)
    elif high == "rise_only":
        s += ["A12=1", "M2=1", "A12=0", "M2=0"] + ["M2=1", "M2=0"] * (F - 1)
    elif high == "fall_only":
        s += ["M2=1", "A12=1", "M2=0", "A12=0"] + ["M2=1", "M2=0"] * F
    return s
def filt_variant(label, high, lstyle, F, hc=1, n=5):
    cmds = ["a12 0", "m 20", "w E000 00", "w C000 01", "w C001 00", "w E001 00", "m 64"]
    for _ in range(n):
        cmds += ["wseq clear"] + [f"wseq add {x} T=1" for x in seg_steps(high, lstyle, F, hc)] + ["wseq run", "r"]
    return (label, cmds)
segs = [
    filt_variant("v1 control: normal high, drop at M2 low, F=16", "normal", "A", 16),
    filt_variant("v2 control: normal high, drop at M2 low, F=15", "normal", "A", 15),
    filt_variant("v3 drop at M2 high, F=16 falls (15 rises)", "normal", "B", 16),
    filt_variant("v4 drop at M2 high, F=15 falls (14 rises)", "normal", "B", 15),
    filt_variant("v5 A12 high across M2 RISE only, F=16", "rise_only", "A", 16),
    filt_variant("v6 A12 high across M2 FALL only, F=16", "fall_only", "A", 16),
    filt_variant("v7 normal high for 6 cycles, F=16", "normal", "A", 16, hc=6),
]
# v8: swallow after $C001: A12 high during $C001
def swal(label, a12_at_c001, extra_hold):
    c = ["a12 0", "m 20", "w E000 00", "w C000 01"]
    if a12_at_c001: c.append("a12 1")
    c.append("w C001 00")
    if extra_hold: c += ["m 2"]
    c += ["a12 0", "w E001 00", "m 20"]
    return (label, c + PULSE * 5)
segs += [swal("v8a $C001 written with A12 HIGH", True, False),
         swal("v8b $C001 written with A12 HIGH, held 2 more M2 cycles", True, True),
         swal("v8c control: $C001 written with A12 LOW", False, False)]
write("53_a12_filter_shape", "# 4-bit-counter model checks. L=1: IRQ at pulse 3 if every pulse counts (first swallowed).", segs)

# ---- 54: $A001 vs IRQ
segs = []
def cpu_a001(d, t_write):
    c = ["w E000 00", "w C000 02", "w C001 01", "w E001 00", "r"]
    t = 1
    while t < 30:
        if t == t_write: c += [f"w A001 {d:02X}", "r"]
        else: c += EV
        t += 1
    return c
for d in (0x00, 0xFF, 0x80, 0x01):
    segs.append((f"cpu L=2: A001={d:02X} at t=3", cpu_a001(d, 3)))
segs.append(("cpu L=2: A001=FF written while /IRQ low (t=20)", cpu_a001(0xFF, 20)))
for d in (0x00, 0xFF):
    c = ["a12 0", "m 20", "w E000 00", "w C000 02", "w C001 00", "w E001 00", "m 64"]
    c += PULSE + [f"w A001 {d:02X}", "r"] + PULSE * 5
    segs.append((f"a12 L=2: A001={d:02X} after pulse 1", c))
write("54_a001_irq", "# $A001 writes during IRQ counting. CPU mode L=2 expects /IRQ at t=14; A12 mode L=2 expects pulse 4.", segs)
# ---- 55: all eight latch bits (CPU mode, expiry at t = 4*(L+1)+2)
segs = []
for L in (0x10, 0x20, 0x40, 0x55, 0x80, 0xAA):
    E = 4 * (L + 1) + 2
    c = ["w E000 00", f"w C000 {L:02X}", "w C001 01", "w E001 00", "r", f"m {E - 4 - 1}", "r"] + EV * 7
    segs.append((f"latch={L:02X} expect first low at t={E}", c))
write("55_latch_bits", "# CPU mode, one latch value per segment; first low expected at t = 4*(L+1)+2 (t from the $C001 write).", segs)
# ---- 56: does $C001 always set the filter counter to 17?  Filter value at $C001 vs whether pulse 1 counts.
segs = []
for n in range(0, 20):   # n low falls (plus the E000/C000 writes) before $C001; pulse after a long low
    segs.append((f"A n={n}: low falls before C001 (A12 reset first)",
                 ["a12 0", "w E000 00", "a12 1", "m 1", "a12 0"] + ([f"m {n}"] if n else []) +
                 ["w C000 00", "w C001 00", "w E001 00", "m 64", "a12 1", "m 2", "a12 0", "m 20", "r"]))
for x in range(10, 18):  # x low falls right before $C001; pulse right after the E001 write
    segs.append((f"B x={x}: filter value at C001, pulse after one more low fall",
                 ["a12 0", "w E000 00", "w C000 00", "a12 1", "m 1", "a12 0"] + ([f"m {x}"] if x else []) +
                 ["w C001 00", "w E001 00", "a12 1", "m 2", "a12 0", "r"]))
write("56_c001_filter_state", "# Pulse 1 after $C001 counts unless the filter was full (>= 16) when $C001 was written. IRQ_N=0 after the pulse means counted.", segs)
print("wrote 51-56")
