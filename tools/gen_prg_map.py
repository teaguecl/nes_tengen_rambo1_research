#!/usr/bin/env python3
"""Generate experiments/07_prg_map.txt: PRG A13-A17 and PRG /CE during CPU read cycles at each
8 KB window, for each $8000 mode (bit 6 = PRG mode; bits 5/7 varied to show independence),
with registers R6, R7 and RF set to distinct values.

Value set 'lo' uses values < 0x20. Value set 'hi' sets bits 5, 6 and 7 of R6, R7 and RF
to see whether bank bits above bit 4 have any effect on the 5 PRG address outputs.
Reads below $8000 are included to check that /CE stays inactive without /ROMSEL.
"""
CTRLS = [0x00, 0x40, 0xA0, 0xE0]                 # bit 6 = PRG mode; bits 5/7 = CHR mode bits
VALS = {"lo": {6: 0x05, 7: 0x0A, 0xF: 0x14},
        "hi": {6: 0x25, 7: 0x4A, 0xF: 0x94}}
READS = ["8000", "A000", "C000", "E000", "0000", "6000"]

out = ["# GENERATED by tools/gen_prg_map.py; do not edit by hand.",
       "# PRG A13-A17 / PRG_CE_N during read cycles vs mode and register values.",
       "# Segment by 'mark' rows: 'ctrl=XX vals=lo|hi'."]
for ctrl in CTRLS:
    for name, vals in VALS.items():
        out.append(f"mark ctrl={ctrl:02X} vals={name}")
        for idx, v in vals.items():
            out.append(f"w 8000 {ctrl | idx:02X}")
            out.append(f"w 8001 {v:02X}")
        for a in READS:
            out.append(f"rd {a}")
open("experiments/07_prg_map.txt", "w").write("\n".join(out) + "\n")
print(f"wrote experiments/07_prg_map.txt: {len(out)} lines")
